// 生成 ps5-loader/payloads.js：把 standalone 队列的两个 payload 源码内联成
// window.STANDALONE_PAYLOADS（index.html 据此设置 window.STANDALONE）。
//
// 为什么需要这个脚本：vendored src/site.js 的 standalone 分支要求
// `window.STANDALONE.payloads = [{ name, args, source }]` 在 module 执行时就绪，
// 而 payload 源码（尤其 payloads/relapse.js 45KB）不适合手写内联进 index.html。
// 这里用 JSON.stringify 把源码转成字符串字面量，与 vendored 的
// `tools/build_standalone.py` 同思路，但保留独立 src/*.js（可 diff、可 verify）。
//
// 用法：node tools/build-page.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const entries = [
  {
    name: "relapse",
    args: ["spawn"],
    file: join(root, "payloads", "relapse.js"),
  },
  {
    name: "elf-send",
    args: [],
    file: join(root, "ludora-payloads", "elf-send.js"),
  },
];

const payloads = entries.map(({ name, args, file }) => ({
  name,
  args,
  source: readFileSync(file, "utf8"),
}));

const out = [
  "// Generated by tools/build-page.mjs — do not edit by hand.",
  "// Inlines the standalone payload queue; index.html builds window.STANDALONE",
  "// from window.STANDALONE_PAYLOADS (see that file's inline script).",
  "window.STANDALONE_PAYLOADS = " + JSON.stringify(payloads, null, 2) + ";",
  "",
].join("\n");

const dest = join(root, "payloads.js");
writeFileSync(dest, out);
console.log("wrote " + dest + " (" + payloads.length + " payloads)");
